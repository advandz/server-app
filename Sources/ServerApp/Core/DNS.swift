import Foundation

/// A wildcard domain answered locally, e.g. every *.test name → 127.0.0.1.
struct DNSDomain: Codable, Hashable, Identifiable {
    var id = UUID()
    var name = "test"
    var address = "127.0.0.1"
    var resolveOnMac = false          // /etc/resolver/<name> points this Mac at the server
}

struct DNSRecord: Codable, Hashable, Identifiable {
    enum Kind: String, Codable, CaseIterable, Identifiable {
        case a = "A", aaaa = "AAAA", cname = "CNAME", txt = "TXT", mx = "MX"
        var id: Self { self }
        var valueHint: String {
            switch self {
            case .a: "192.168.1.10"
            case .aaaa: "fd00::10"
            case .cname: "target.example.test"
            case .txt: "v=spf1 -all"
            case .mx: "mail.example.test"
            }
        }
    }
    var id = UUID()
    var kind: Kind = .a
    var name = ""
    var value = ""
    var priority = 10                 // MX only
}

/// DNS server settings (Homebrew dnsmasq).
struct DNSSettings: Codable, Hashable {
    var port = 53
    var allowNetwork = false          // answer other devices on the network, not just this Mac
    var useCustomUpstream = false
    var upstream = "1.1.1.1 1.0.0.1"  // space separated; otherwise the Mac's own DNS servers
    var cacheSize = 1000
    var answerFromHostsFile = false
    var logQueries = false
    var domains: [DNSDomain] = [DNSDomain()]
    var records: [DNSRecord] = []

    init() {}
    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        port = (try? c.decode(Int.self, forKey: .port)) ?? 53
        allowNetwork = (try? c.decode(Bool.self, forKey: .allowNetwork)) ?? false
        useCustomUpstream = (try? c.decode(Bool.self, forKey: .useCustomUpstream)) ?? false
        upstream = (try? c.decode(String.self, forKey: .upstream)) ?? "1.1.1.1 1.0.0.1"
        cacheSize = (try? c.decode(Int.self, forKey: .cacheSize)) ?? 1000
        answerFromHostsFile = (try? c.decode(Bool.self, forKey: .answerFromHostsFile)) ?? false
        logQueries = (try? c.decode(Bool.self, forKey: .logQueries)) ?? false
        domains = (try? c.decode([DNSDomain].self, forKey: .domains)) ?? [DNSDomain()]
        records = (try? c.decode([DNSRecord].self, forKey: .records)) ?? []
    }

    var upstreamServers: [String] {
        upstream.split(whereSeparator: { $0 == " " || $0 == "," || $0 == "\n" }).map(String.init).filter { !$0.isEmpty }
    }
}

enum DNSServer {
    static let formula = "dnsmasq"
    static var dir: String { Paths.conf + "/dns" }
    static var confFile: String { dir + "/dnsmasq.conf" }
    static var pidFile: String { Paths.run + "/dnsmasq.pid" }
    static var logFile: String { Paths.logs + "/dns.log" }
    static var startLog: String { Paths.logs + "/dns_start.log" }

    static func binary(prefix: String) -> String { prefix + "/opt/dnsmasq/sbin/dnsmasq" }

    static func isValidName(_ s: String) -> Bool { HostEntry.isValidName(s) }

    static func config(_ s: DNSSettings) -> String {
        var c = """
        # Generated by Server. Do not edit: changes are overwritten.
        port=\(s.port)
        pid-file=\(pidFile)
        log-facility=\(logFile)
        cache-size=\(s.cacheSize)
        domain-needed
        bogus-priv

        """
        if s.allowNetwork { c += "bind-dynamic\n" } else { c += "listen-address=127.0.0.1,::1\nbind-interfaces\n" }
        if s.logQueries { c += "log-queries\n" }
        if !s.answerFromHostsFile { c += "no-hosts\n" }
        if s.useCustomUpstream, !s.upstreamServers.isEmpty {
            c += "no-resolv\n" + s.upstreamServers.map { "server=\($0)" }.joined(separator: "\n") + "\n"
        } else {
            c += "resolv-file=/etc/resolv.conf\n"
        }
        c += "\n# Domains\n"
        for d in s.domains where isValidName(d.name) && HostEntry.isValidAddress(d.address) {
            c += "address=/\(d.name)/\(d.address)\n"
        }
        c += "\n# Records\n"
        for r in s.records where isValidName(r.name) && !r.value.isEmpty {
            // Values go into the config as they are, so each kind must hold only what it should.
            switch r.kind {
            case .a, .aaaa: if HostEntry.isValidAddress(r.value) { c += "host-record=\(r.name),\(r.value)\n" }
            case .cname: if isValidName(r.value) { c += "cname=\(r.name),\(r.value)\n" }
            case .txt:
                let text = r.value.filter { !$0.isNewline && $0 != "\"" && $0 != "\0" }
                if !text.isEmpty { c += "txt-record=\(r.name),\"\(text)\"\n" }
            case .mx: if isValidName(r.value) { c += "mx-host=\(r.name),\(r.value),\(min(max(r.priority, 0), 65535))\n" }
            }
        }
        return c
    }

    /// Writes the config and checks it with `dnsmasq --test`. Returns an error message or nil.
    static func writeConfig(_ s: DNSSettings, prefix: String) async -> String? {
        do { try Paths.write(config(s), to: confFile) } catch { return error.localizedDescription }
        let r = await Shell.run(binary(prefix: prefix), ["--test", "--conf-file=\(confFile)"])
        return r.ok ? nil : r.output.trimmingCharacters(in: .whitespacesAndNewlines)
    }

    static func arguments() -> [String] { ["--conf-file=\(confFile)"] }

    /// Asks the server for a name, like `dig @127.0.0.1 name`.
    static func lookUp(_ name: String, type: String = "A", port: Int) async -> String {
        let r = await Shell.run("/usr/bin/dig", ["@127.0.0.1", "-p", String(port), "+short", "+time=2", "+tries=1", name, type])
        let out = r.output.trimmingCharacters(in: .whitespacesAndNewlines)
        return out.isEmpty ? "No answer" : out
    }

    // MARK: /etc/resolver (send *.domain lookups on this Mac to the server)

    static func resolverFile(_ domain: String) -> String { "/etc/resolver/\(domain)" }

    static func resolverInstalled(_ domain: String) -> Bool {
        let text = (try? String(contentsOfFile: resolverFile(domain), encoding: .utf8)) ?? ""
        return text.contains("nameserver 127.0.0.1")
    }

    /// Commands (run as root) that make the resolver files match the domains' settings.
    /// `rewrite` replaces existing files too (after the port changed).
    static func resolverCommands(_ s: DNSSettings, rewrite: Bool = false) -> [[String]] {
        var cmds: [[String]] = []
        for d in s.domains where isValidName(d.name) {
            let installed = resolverInstalled(d.name)
            if d.resolveOnMac && (!installed || rewrite) {
                let staged = Paths.work + "/resolver-\(d.name)"
                try? "# Added by Server\nnameserver 127.0.0.1\nport \(s.port)\n".write(toFile: staged, atomically: true, encoding: .utf8)
                cmds += [["/bin/mkdir", "-p", "/etc/resolver"], ["/bin/cp", staged, resolverFile(d.name)],
                         ["/bin/chmod", "644", resolverFile(d.name)]]
            } else if !d.resolveOnMac && installed {
                cmds.append(["/bin/rm", "-f", resolverFile(d.name)])
            }
        }
        return cmds
    }
}
