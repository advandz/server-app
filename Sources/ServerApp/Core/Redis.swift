import Foundation

/// Redis server settings (Homebrew redis).
struct RedisSettings: Codable, Hashable {
    var port = 6379
    var allowNetwork = false              // listen on all addresses (needs a password)
    var password = ""                     // empty = none (this Mac only)
    var maxMemoryMB = 0                   // 0 = unlimited
    var evictionPolicy = "noeviction"
    var snapshots = true                  // RDB snapshots: save to disk now and then and on stop
    var appendOnly = false                // AOF: log every write
    var databases = 16

    init() {}
    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        port = (try? c.decode(Int.self, forKey: .port)) ?? 6379
        allowNetwork = (try? c.decode(Bool.self, forKey: .allowNetwork)) ?? false
        password = (try? c.decode(String.self, forKey: .password)) ?? ""
        maxMemoryMB = (try? c.decode(Int.self, forKey: .maxMemoryMB)) ?? 0
        evictionPolicy = (try? c.decode(String.self, forKey: .evictionPolicy)) ?? "noeviction"
        snapshots = (try? c.decode(Bool.self, forKey: .snapshots)) ?? true
        appendOnly = (try? c.decode(Bool.self, forKey: .appendOnly)) ?? false
        databases = (try? c.decode(Int.self, forKey: .databases)) ?? 16
    }
}

enum RedisServer {
    static let formula = "redis"
    static func binary(prefix: String) -> String { prefix + "/opt/redis/bin/redis-server" }
    static func cli(prefix: String) -> String { prefix + "/opt/redis/bin/redis-cli" }
    static var confFile: String { Paths.conf + "/redis/redis.conf" }
    static var pidFile: String { Paths.run + "/redis.pid" }
    static var logFile: String { Paths.logs + "/redis.log" }
    static var startLog: String { Paths.logs + "/redis_start.log" }
    static var dataDir: String { Paths.data + "/redis" }

    static let policies = ["noeviction", "allkeys-lru", "allkeys-lfu", "allkeys-random", "volatile-lru", "volatile-lfu", "volatile-random", "volatile-ttl"]

    private static func quoted(_ s: String) -> String {
        "\"" + s.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"")
            .replacingOccurrences(of: "\n", with: "\\n").replacingOccurrences(of: "\r", with: "\\r") + "\""
    }

    static func config(_ s: RedisSettings) -> String {
        var c = """
        # Generated by Server. Do not edit: changes are overwritten.
        port \(s.port)
        \(s.allowNetwork ? "bind * -::*" : "bind 127.0.0.1 -::1")
        protected-mode yes
        daemonize yes
        pidfile \(quoted(pidFile))
        logfile \(quoted(logFile))
        dir \(quoted(dataDir))
        databases \(max(1, s.databases))

        """
        if !s.password.isEmpty { c += "requirepass \(quoted(s.password))\n" }
        if s.maxMemoryMB > 0 { c += "maxmemory \(s.maxMemoryMB)mb\nmaxmemory-policy \(s.evictionPolicy)\n" }
        c += s.snapshots ? "save 3600 1 300 100 60 10000\n" : "save \"\"\n"
        c += "appendonly \(s.appendOnly ? "yes" : "no")\n"
        return c
    }

    /// Writes the config (readable only by you: it can hold the password).
    static func writeConfig(_ s: RedisSettings) throws {
        try Paths.write(config(s), to: confFile)
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: confFile)
        try FileManager.default.createDirectory(atPath: dataDir, withIntermediateDirectories: true)
    }

    /// Runs redis-cli against the server. The password goes through the environment, not the
    /// command line (where other users could read it).
    static func run(_ args: [String], settings: RedisSettings, prefix: String) async -> ShellResult {
        var env: [String: String] = [:]
        if !settings.password.isEmpty { env["REDISCLI_AUTH"] = settings.password }
        return await Shell.run(cli(prefix: prefix), ["-h", "127.0.0.1", "-p", String(settings.port), "--no-auth-warning"] + args, env: env)
    }

    struct Info: Sendable {
        var version = "", role = ""
        var uptime = 0, clients = 0, opsPerSecond = 0
        var usedMemory = "", peakMemory = "", maxMemory = ""
        var commands = 0, hits = 0, misses = 0
        var databases: [(name: String, keys: Int, expires: Int)] = []
        var totalKeys: Int { databases.reduce(0) { $0 + $1.keys } }
    }

    static func info(settings: RedisSettings, prefix: String) async -> Info? {
        let r = await run(["INFO"], settings: settings, prefix: prefix)
        guard r.ok, r.output.contains("redis_version") else { return nil }
        var map: [String: String] = [:]
        var info = Info()
        for line in r.output.split(whereSeparator: \.isNewline) where !line.hasPrefix("#") {
            guard let colon = line.firstIndex(of: ":") else { continue }
            let key = String(line[..<colon]), value = String(line[line.index(after: colon)...]).trimmingCharacters(in: .whitespaces)
            map[key] = value
            if key.hasPrefix("db"), Int(key.dropFirst(2)) != nil {
                // db0:keys=3,expires=1,avg_ttl=0
                let parts = value.split(separator: ",").reduce(into: [String: Int]()) { d, p in
                    let kv = p.split(separator: "="); if kv.count == 2 { d[String(kv[0])] = Int(kv[1]) }
                }
                info.databases.append((key, parts["keys"] ?? 0, parts["expires"] ?? 0))
            }
        }
        info.version = map["redis_version"] ?? ""
        info.role = map["role"] ?? ""
        info.uptime = Int(map["uptime_in_seconds"] ?? "") ?? 0
        info.clients = Int(map["connected_clients"] ?? "") ?? 0
        info.opsPerSecond = Int(map["instantaneous_ops_per_sec"] ?? "") ?? 0
        info.usedMemory = map["used_memory_human"] ?? ""
        info.peakMemory = map["used_memory_peak_human"] ?? ""
        info.maxMemory = map["maxmemory_human"] ?? ""
        info.commands = Int(map["total_commands_processed"] ?? "") ?? 0
        info.hits = Int(map["keyspace_hits"] ?? "") ?? 0
        info.misses = Int(map["keyspace_misses"] ?? "") ?? 0
        return info
    }

    /// Splits a console line into arguments, honouring "double" and 'single' quotes.
    static func tokenize(_ line: String) -> [String]? {
        var tokens: [String] = [], current = "", quote: Character?, any = false
        for ch in line {
            if let q = quote {
                if ch == q { quote = nil } else { current.append(ch) }
            } else if ch == "\"" || ch == "'" {
                quote = ch; any = true
            } else if ch == " " || ch == "\t" {
                if any || !current.isEmpty { tokens.append(current); current = ""; any = false }
            } else {
                current.append(ch)
            }
        }
        if quote != nil { return nil }                      // unterminated quote
        if any || !current.isEmpty { tokens.append(current) }
        return tokens
    }
}
