"""Builds Support/Localization/<lang>.lproj/Localizable.strings from keys.json (the English text)
and one translation file per language (Support/Localization/Translations/<lang>.txt, lines
"index|translation"). Checks that every translation keeps the same format placeholders."""
import json, re, sys, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
loc = os.path.join(root, 'Support', 'Localization')
keys = json.load(open(os.path.join(loc, 'keys.json')))
ph = lambda s: sorted(re.sub(r'%\d+\$', '%', m) for m in re.findall(r'%(?:\d+\$)?(?:lld|@|d)', s))
def esc(s): return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
bad = 0
langs = sorted(f[:-4] for f in os.listdir(os.path.join(loc, 'Translations')) if f.endswith('.txt'))
for lang in langs:
    tr = {}
    for line in open(os.path.join(loc, 'Translations', lang + '.txt'), encoding='utf-8'):
        line = line.rstrip('\n')
        if not line: continue
        i, _, t = line.partition('|')
        tr[int(i)] = t
    out = ['/* Generated by Tools/make-strings.py. Keys are the English text. */', '']
    missing = 0
    for i, k in enumerate(keys):
        t = tr.get(i)
        if t is None: missing += 1; t = k
        elif ph(t) != ph(k) and not (set(ph(t)) <= set(ph(k))):
            print(f'{lang}: placeholder mismatch #{i}: {k!r} -> {t!r}'); bad += 1
        out.append(f'"{esc(k)}" = "{esc(t)}";')
    d = os.path.join(loc, lang + '.lproj'); os.makedirs(d, exist_ok=True)
    open(os.path.join(d, 'Localizable.strings'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print(f'{lang}: {len(keys)} keys, {missing} untranslated')
sys.exit(1 if bad else 0)
