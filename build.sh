# Builds a universal (Apple Silicon + Intel) Server.app bundle into ./build
set -euo pipefail
cd "$(dirname "$0")"

APP_NAME="Server"
BUNDLE_ID="com.local.serverapp"
VERSION="1.1.0"
OUT="build/${APP_NAME}.app"

echo "→ Compiling (arm64 + x86_64)…"
swift build -c release --arch arm64 --arch x86_64
BIN="$(swift build -c release --arch arm64 --arch x86_64 --show-bin-path)/ServerApp"

echo "→ Assembling ${OUT}"
rm -rf "$OUT"
mkdir -p "$OUT/Contents/MacOS" "$OUT/Contents/Resources"
cp "$BIN" "$OUT/Contents/MacOS/${APP_NAME}"

# Languages: one Support/Localization/<language>.lproj per translation.
LOCALIZATION_PLIST=""
for lproj in Support/Localization/*.lproj; do
  lang="$(basename "$lproj" .lproj)"
  LOCALIZATION_PLIST="${LOCALIZATION_PLIST}<string>${lang}</string>"
done

cat > "$OUT/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>${APP_NAME}</string>
  <key>CFBundleDisplayName</key><string>${APP_NAME}</string>
  <key>CFBundleExecutable</key><string>${APP_NAME}</string>
  <key>CFBundleIdentifier</key><string>${BUNDLE_ID}</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>${VERSION}</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>LSMinimumSystemVersion</key><string>14.0</string>
  <key>LSApplicationCategoryType</key><string>public.app-category.developer-tools</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>NSPrincipalClass</key><string>NSApplication</string>
  <key>NSLocationUsageDescription</key><string>Server uses your location only so macOS lets it show the name of the Wi-Fi network you're connected to.</string>
  <key>NSHumanReadableCopyright</key><string>Copyright © 2026 Advandz Technologies, LLC</string>
  <key>CFBundleDevelopmentRegion</key><string>en</string>
  <key>CFBundleLocalizations</key><array>${LOCALIZATION_PLIST}</array>
  <key>CFBundleIconFile</key><string>AppIcon</string>
</dict>
</plist>
PLIST

# Translations (Localizable.strings per language, generated by Tools/make-strings.py).
for lproj in Support/Localization/*.lproj; do
  cp -R "$lproj" "$OUT/Contents/Resources/"
done

# Official Apache / nginx / MySQL logos shown in the sidebar and server pages.
mkdir -p "$OUT/Contents/Resources/Logos"
cp Resources/Logos/*.svg "$OUT/Contents/Resources/Logos/"

# App icon. Resources/AppIcon.icon is an Icon Composer document (Liquid Glass, with
# Default, Dark, Clear and Tinted appearances). Compiling it needs Xcode's actool, which
# also writes an AppIcon.icns for macOS 14/15. Without Xcode the static .icns is used.
cp Resources/AppIcon.icns "$OUT/Contents/Resources/AppIcon.icns"
if xcrun --find actool >/dev/null 2>&1; then
  echo "→ Compiling Liquid Glass icon"
  PARTIAL="$(mktemp -t serverapp-icon).plist"
  if xcrun actool Resources/AppIcon.icon \
      --compile "$OUT/Contents/Resources" \
      --platform macosx --target-device mac --minimum-deployment-target 14.0 \
      --app-icon AppIcon --include-all-app-icons \
      --output-partial-info-plist "$PARTIAL" \
      --errors --warnings >/dev/null; then
    /usr/libexec/PlistBuddy -c "Add :CFBundleIconName string AppIcon" "$OUT/Contents/Info.plist"
  else
    echo "  actool failed; using the static AppIcon.icns" >&2
  fi
  rm -f "$PARTIAL"
else
  echo "→ Using static icon (install Xcode to compile the Liquid Glass AppIcon.icon)"
fi

codesign --force --sign - "$OUT" >/dev/null
codesign --verify --strict "$OUT"
echo "→ Architectures: $(lipo -archs "$OUT/Contents/MacOS/${APP_NAME}")"
echo "✓ Built $OUT"

# Disk image: the app plus a shortcut to /Applications to drag it onto. This is what
# gets attached to a GitHub release, and what the app's updater downloads.
DMG="build/${APP_NAME}-${VERSION}.dmg"
echo "→ Packing $DMG"
STAGE="$(mktemp -d)"
trap 'rm -rf "${STAGE:?}"' EXIT
ditto "$OUT" "$STAGE/${APP_NAME}.app"
ln -s /Applications "$STAGE/Applications"
rm -f "$DMG"
hdiutil create -volname "${APP_NAME} ${VERSION}" -srcfolder "$STAGE" -fs HFS+ -format UDZO -ov "$DMG" >/dev/null
hdiutil verify "$DMG" >/dev/null
echo "✓ Packed $DMG"
